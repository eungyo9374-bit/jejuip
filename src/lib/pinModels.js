// 옆모습(평면 도형)을 두께만큼 밀어낸 판 — 돛·화살표·박공지붕 등
function prism(pts, depth) {
  const g = new THREE.ExtrudeGeometry(new THREE.Shape(pts.map(([x, y]) => new THREE.Vector2(x, y))), { depth, bevelEnabled: false })
  g.translate(0, 0, -depth / 2)
  return g
}

const M = new THREE.Matrix4(), Q = new THREE.Quaternion(), E = new THREE.Euler(), P = new THREE.Vector3(), S = new THREE.Vector3()
// 도형 하나를 자리·크기·회전에 맞춰 놓고 색을 칠해요 (faceColor: 삼각형마다 다른 색 — 줄무늬 파라솔 등)
function part(geo, color, pos = [0, 0, 0], scl = [1, 1, 1], rot = [0, 0, 0], faceColor) {
  const g = geo.index ? geo.toNonIndexed() : geo.clone()
  for (const k of Object.keys(g.attributes)) if (k !== 'position' && k !== 'normal') g.deleteAttribute(k)
  g.clearGroups()
  g.applyMatrix4(M.compose(P.set(...pos), Q.setFromEuler(E.set(...rot)), S.set(...scl)))
  const n = g.attributes.position.count, arr = new Float32Array(n * 3), c = new THREE.Color()
  for (let i = 0; i < n; i++) { c.set(faceColor ? faceColor(Math.floor(i / 3)) ?? color : color); arr.set([c.r, c.g, c.b], i * 3) }
  g.setAttribute('color', new THREE.BufferAttribute(arr, 3))
  // 모서리가 적은 기둥·원뿔(육각 돌기둥, 기와지붕 등)은 면이 또렷하게 보이도록 각진 음영
  if ((geo.parameters?.radialSegments ?? 99) <= 8) g.computeVertexNormals()
  return g
}
